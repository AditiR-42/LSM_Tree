#!/bin/bash

# --- Configuration ---
# Input workload file (containing 'p' commands)
# Assumes this file is in the SAME directory as the script
WORKLOAD_FILE="put_1mb.txt"

DATABASE_EXEC_REL_PATH="../lsm_tree_app"

# Output file for timing and program logs
OUTPUT_FILE="$(basename "$WORKLOAD_FILE" .txt)_output_v2.log"
# --- End Configuration ---

# Get the directory where the script is located
script_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# Construct full paths based on the script's location
full_workload_path="${script_dir}/${WORKLOAD_FILE}"
full_database_exec_path="${script_dir}/${DATABASE_EXEC_REL_PATH}"
full_output_path="${script_dir}/${OUTPUT_FILE}"

echo "--- Running Put Workload ---"
echo "Script Directory: ${script_dir}"
echo "Workload File:    ${full_workload_path}"
echo "Database Exec:    ${full_database_exec_path}"
echo "Output Log File:  ${full_output_path}"
echo "----------------------------"

# --- Pre-run Checks ---
if [ ! -f "$full_workload_path" ]; then
    echo "ERROR: Workload file not found: ${full_workload_path}"
    exit 1
fi

# Check if the database executable exists and is executable
if [ ! -x "$full_database_exec_path" ]; then
    echo "ERROR: Database executable not found or not executable: ${full_database_exec_path}"
    # Try common alternative location if the first one failed
    alt_database_exec_path="${script_dir}/database"
     if [ -x "$alt_database_exec_path" ]; then
         echo "Info: Found database executable in script directory: ${alt_database_exec_path}"
         full_database_exec_path="$alt_database_exec_path"
     else
        echo "ERROR: Also not found at ${alt_database_exec_path}"
        exit 1
     fi
fi


# --- Execution and Timing ---
echo "Starting database execution and timing..."
echo "Output will be saved to ${full_output_path}"

# The core command:
# { time ... ; } captures the time output (which goes to stderr by default)
# > redirects stdout of the command inside {} to the output file
# 2>&1 redirects stderr (including time's output) to the same file as stdout
{ time "${full_database_exec_path}" < "${full_workload_path}" ; } > "${full_output_path}" 2>&1
EXIT_CODE=$?

echo "Database execution finished."

# --- Result ---
if [ $EXIT_CODE -eq 0 ]; then
    echo "SUCCESS: Put workload completed successfully."
    echo "Timing information and program output saved to: ${full_output_path}"
    # Display the time output from the log file for convenience
    echo "--- Timing Summary (from log) ---"
    grep -E 'real|user|sys' "${full_output_path}" # Extracts time lines
    echo "---------------------------------"
else
    echo "ERROR: Database program exited with error code ${EXIT_CODE}."
    echo "Check the output log for details: ${full_output_path}"
fi

echo "NOTE: Data generated by the workload has NOT been cleaned up."
echo "Data directory should remain populated."

# Exit with the database program's exit code
exit $EXIT_CODE